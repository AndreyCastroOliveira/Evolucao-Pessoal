#Faça um programa que leia o valor de um produto e mostre seu novo valor, com 5% de desconto.

P = float(input('Digite o valor do produto: '))

D = P * 0.05

print(f'O valor do produto com desconto e {D} reais.')

#Neste programa, basta apenas usar a formula de desconto, que é o valor do produto multiplicado por 0.05, que é o mesmo que 5%.

#a formula e dada por: Desconto = Valor do produto * Valor do desconto / 100